export function esc(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function extractPreviewTierName(label, fallback = 'High') {
  const m = /\((off|low|medium|high|extra|xhigh|max|minimal)(?:\s+thinking)?\)$/i.exec(String(label || ''));
  return m ? (TIER_NAMES[m[1].toLowerCase()] || m[1]) : fallback;
}

export function buildDefaultPreviewSelectionMap(tierOverrides) {
  const out = {};
  const map = tierOverrides && typeof tierOverrides === 'object' ? tierOverrides : {};
  for (const [name, , fallbackTier] of PREVIEW_MODEL_LIST) {
    const grp = PREVIEW_SAMPLE_GROUPS[name];
    const prefTier = typeof map[name] === 'string' ? map[name].toLowerCase() : fallbackTier;
    const hit =
      grp.items.find((it) => it.tier.toLowerCase() === prefTier) ||
      grp.items.find((it) => it.tier.toLowerCase() === fallbackTier) ||
      grp.items[0];
    out[name] = hit.label;
  }
  return out;
}
